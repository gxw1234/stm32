{
    uint16_t i, j;
    LCD_Set_Window(0, 0, LCD_WIDTH-1, LCD_HEIGHT-1);
    
    for(i = 0; i < LCD_WIDTH; i++)
    {
        for(j = 0; j < LCD_HEIGHT; j++)
        {
            LCD_Write_Data_16Bit(color);
        }
    }
}

/* 画点函数 */
void LCD_Draw_Point(uint16_t x, uint16_t y, uint16_t color)
{
    if(x >= LCD_WIDTH || y >= LCD_HEIGHT) return;
    
    LCD_Set_Window(x, y, x, y);
    LCD_Write_Data_16Bit(color);
}

/* 画线函数 */
void LCD_Draw_Line(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2, uint16_t color)
{
    int16_t dx = x2 - x1;
    int16_t dy = y2 - y1;
    int16_t sx = (dx > 0) ? 1 : ((dx < 0) ? -1 : 0);
    int16_t sy = (dy > 0) ? 1 : ((dy < 0) ? -1 : 0);
    dx = (dx > 0) ? dx : -dx;
    dy = (dy > 0) ? dy : -dy;
    
    int16_t err = dx - dy;
    int16_t e2;
    
    while(1)
    {
        LCD_Draw_Point(x1, y1, color);
        if(x1 == x2 && y1 == y2) break;
        
        e2 = 2 * err;
        if(e2 > -dy)
        {
            err -= dy;
            x1 += sx;
        }
        
        if(e2 < dx)
        {
            err += dx;
            y1 += sy;
        }
    }
}

/* 画一个填充的矩形 */
void LCD_Fill_Rect(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2, uint16_t color)
{
    LCD_Set_Window(x1, y1, x2, y2);
    
    for(uint16_t i = 0; i < (x2-x1+1)*(y2-y1+1); i++)
    {
        LCD_Write_Data_16Bit(color);
    }
}

/* 初始化ST7789 LCD */
void LCD_Init(void)
{
    // 复位LCD
    LCD_Reset();
    
    // 退出睡眠模式
    LCD_Write_Cmd(ST7789_SLPOUT);
    LCD_Delay(120);
    
    // 设置像素格式，16位RGB565
    LCD_Write_Cmd(ST7789_COLMOD);
    LCD_Write_Data(0x05);
    
    // 设置显示方向
    LCD_Write_Cmd(ST7789_MADCTL);
    LCD_Write_Data(0x08); // 0x08方向，如有需要可以调整
    
    // 开启显示反转
    LCD_Write_Cmd(ST7789_INVON);
    
    // 开启显示
    LCD_Write_Cmd(ST7789_NORON);
    LCD_Write_Cmd(ST7789_DISPON);
    
    // 打开背光
    LCD_BLK_ON;
    
    // 屏幕初始化，清为黑色
    LCD_Clear(COLOR_BLACK);
}

/* 显示ASCII字符 */
void LCD_Show_Char(uint16_t x, uint16_t y, uint8_t ch, uint16_t color, uint16_t bg_color, uint8_t size, uint8_t size_mult)
{
    // 确保缩放因子至少为1
    if(size_mult == 0) size_mult = 1;
    
    // 计算缩放后的字符大小
    uint16_t char_width = (size == FONT_1206) ? 6 * size_mult : 8 * size_mult;
    uint16_t char_height = size * size_mult;
    
    if(x > LCD_WIDTH-char_width || y > LCD_HEIGHT-char_height)
        return;
    
    ch = ch - ' '; // 得到相对于空格的字符偏移量
    
    if(size == FONT_1206)
    {
        for(uint8_t t = 0; t < 12; t++) // 扫描12行
        {
            uint8_t temp = ascii_1206[ch][t]; // 获取字符的数据
            for(uint8_t i = 0; i < 6; i++) // 一行6个点
            {
                // 计算缩放后的起始坐标
                uint16_t new_x = x + i * size_mult;
                uint16_t new_y = y + t * size_mult;
                
                // 绘制size_mult x size_mult大小的方块代表一个原始像素
                for(uint8_t m = 0; m < size_mult; m++)
                {
                    for(uint8_t n = 0; n < size_mult; n++)
                    {
                        if(temp & 0x80) // 有数据的点，显示字符颜色
                            LCD_Draw_Point(new_x+m, new_y+n, color);
                        else // 没有数据的点，显示背景色
                            LCD_Draw_Point(new_x+m, new_y+n, bg_color);
                    }
                }
                
                temp <<= 1; // 数据左移1位
            }
        }
    }
    else // 目前只支持FONT_1206的缩放
    {
        LCD_Show_Char(x, y, ch+' ', color, bg_color, FONT_1206, size_mult);
    }
}

/* 显示ASCII字符串 */
void LCD_Show_String(uint16_t x, uint16_t y, const char *str, uint16_t color, uint16_t bg_color, uint8_t size, uint8_t size_mult)
{
    // 确保缩放因子至少为1
    if(size_mult == 0) size_mult = 1;
    
    // 计算字符宽度（基于字体大小和缩放因子）
    uint16_t char_width = (size == FONT_1206) ? 6 * size_mult : 8 * size_mult;
    uint16_t char_height = size * size_mult;
    
    while(*str != '\0')
    {
        LCD_Show_Char(x, y, *str, color, bg_color, size, size_mult);
        x += char_width; // 水平方向移动字符宽度
        if(x > LCD_WIDTH-char_width) // 自动换行
        {
            x = 0;
            y += char_height;
        }
        str++;
    }
}

/* 显示中文字符(简单版本，只支持已定义的几个字) */
void LCD_Show_Chinese(uint16_t x, uint16_t y, uint8_t index, uint16_t color, uint16_t bg_color, uint8_t size_mult)
{
    if(index >= 4) // 超过定义的中文数量
        return;
    
    // 检查显示区域是否超出屏幕范围
    if(size_mult == 0) size_mult = 1; // 防止缩放因子为0
    uint16_t width = 16 * size_mult;  // 缩放后的字符宽度
    uint16_t height = 16 * size_mult; // 缩放后的字符高度
    
    if(x > LCD_WIDTH-width || y > LCD_HEIGHT-height)
        return;
    
    for(uint8_t t = 0; t < 32; t++) // 扫描32行原始数据
    {
        uint8_t temp = chinese_1616[index][t]; // 获取字符的数据
        
        for(uint8_t i = 0; i < 8; i++) // 一行8个原始点
        {
            uint16_t new_x = x + ((t%2)*8+i) * size_mult; // 计算缩放后的X坐标
            uint16_t new_y = y + (t/2) * size_mult;       // 计算缩放后的Y坐标
            
            // 绘制size_mult x size_mult大小的方块代表一个原始像素
            for(uint8_t m = 0; m < size_mult; m++)
            {
                for(uint8_t n = 0; n < size_mult; n++)
                {
                    if(temp & 0x80) // 有数据的点，显示字符颜色
                        LCD_Draw_Point(new_x+m, new_y+n, color);
                    else // 没有数据的点，显示背景色
                        LCD_Draw_Point(new_x+m, new_y+n, bg_color);
                }
            }
            
            temp <<= 1; // 数据左移1位
        }
    }
}

/* 显示时间样例 */
void LCD_Show_Time(uint16_t x, uint16_t y, uint8_t hour, uint8_t min, uint8_t sec, uint16_t color, uint16_t bg_color, uint8_t size_mult)
{
    char time_str[9];
    sprintf(time_str, "%02d:%02d:%02d", hour, min, sec);
    LCD_Show_String(x, y, time_str, color, bg_color, FONT_1206, size_mult);
}

/* LCD任务主函数 */
void LCD_Task(void *pvParameters)
{
    printf("LCD任务开始运行...\r\n");
    
    // 初始化LCD
    LCD_Init();
    
    // 清屏，黑色背景
    LCD_Clear(COLOR_BLACK);
    
    // 计算中心位置 - 以显示英文
    uint16_t text_x = (LCD_WIDTH - 12*7)/2;  // 居中显示 "ST7789" 7个字符
    uint16_t text_y = (LCD_HEIGHT - 12)/2 - 50; // 在屏幕中心偏上一点
    
    // 显示英文文本 - 原始大小
    LCD_Show_String(text_x, text_y, "ST7789", COLOR_WHITE, COLOR_BLACK, FONT_1206, 1);
    
    // 显示放大1.5倍的字体 (50%增大)
    LCD_Show_String(80, text_y + 25, "LCD", COLOR_GREEN, COLOR_BLACK, FONT_1206, 2);
    
    // 显示放大2倍的字体
    LCD_Show_String(60, text_y + 55, "Demo", COLOR_CYAN, COLOR_BLACK, FONT_1206, 2);
    
    // 显示可选的字体大小示例
    LCD_Show_String(20, text_y + 85, "Size 1", COLOR_RED, COLOR_BLACK, FONT_1206, 1);
    LCD_Show_String(85, text_y + 85, "Size 2", COLOR_YELLOW, COLOR_BLACK, FONT_1206, 2);

    // 初始化时间显示变量
    uint8_t hour = 15; // 初始化为当前时间 15点
    uint8_t min = 23;
    uint8_t sec = 42;
    
    // 要清除的时间区域的左上角坐标
    uint16_t time_x = LCD_WIDTH - 70; // 右上角时间显示的X坐标
    uint16_t time_y = 5;              // 右上角时间显示的Y坐标
    
    // 黑色矩形清除时间区域（防止自刷时文字重叠）
    LCD_Fill_Rect(time_x - 5, time_y - 2, LCD_WIDTH - 2, time_y + 14, COLOR_BLACK);
    
    // 显示初始时间
    LCD_Show_Time(time_x, time_y, hour, min, sec, COLOR_WHITE, COLOR_BLACK, 1);
    
    // 输出调试信息
    printf("LCD 显示完成\r\n");
    
    while(1)
    {
        // 更新时间
        sec++;
        if(sec >= 60) { sec = 0; min++; }
        if(min >= 60) { min = 0; hour++; }
        if(hour >= 24) { hour = 0; }
        
        // 清除上一次显示的时间
        LCD_Fill_Rect(time_x - 5, time_y - 2, LCD_WIDTH - 2, time_y + 14, COLOR_BLACK);
        
        // 显示新的时间
        LCD_Show_Time(time_x, time_y, hour, min, sec, COLOR_WHITE, COLOR_BLACK, 1);
        
        // 每秒更新一次
        vTaskDelay(1000 / portTICK_PERIOD_MS);
    }
}